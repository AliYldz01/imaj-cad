with sync_playwright() as p:
    A = App(p, mobile=True); S = Asm(A)
    to_lib(A, pin_doc())
    setdoc(A, plate_doc())
    # (Ekstrüzyon düzenlenmez: Instant3D oku montajda kalıp dokunmayı engelliyor — bkz. d9_i3d.py)
    # 1) montajı aç + bileşen ekle (dokunma)
    S.open()
    chk("F1 telefonda Montajı Aç (tepsi)", S.on())
    P1 = S.add_current(); PN = S.add_lib("Pim")
    chk("F1 iki bileşen dokunarak eklendi", len(S.comps()) == 2, [c["name"] for c in S.comps()])
    # telefonda görünüm: sığdır (görünüm küpü izo)
    loc = A.pg.locator(".vcube .iso")
    if loc.count():
        loc.first.tap(); time.sleep(0.5)
    A.pg.screenshot(path=OUT + "/F_tel1.png")
    # 2) eşleşme: dokunarak yüz seçimi
    A.cmd("Eşleşme")
    pmh = A.ev("(()=>{const r=document.querySelector('#side').getBoundingClientRect();return [r.top, innerHeight]})()")
    s1 = S.click_local(PN["id"], [3.5, 20, 3.5])
    s2 = S.click_local(P1["id"], [30 - 3.5, 8, -30 - 3.5])
    txt = A.pmtext()
    A.btn("#pm-ok"); A.wait(0.8)
    ms = S.mates()
    chk("F2 telefonda dokunarak eş merkezli eşleşme", ms and ms[0]["type"] == "concentric" and abs(S.comps()[1]["p"][0] - 30) < 0.05, (txt[:120].replace("\n", " | "), s1, s2, pmh, [c["p"] for c in S.comps()]))
    if S.pm_open():
        A.btn("#pm-cancel"); A.wait(0.4)
    # 3) bileşeni parmakla sürükle (eş merkezli → yalnız eksen boyunca)
    p0 = S.comps()[1]["p"]
    s = S.screen(S.world(PN["id"], [3.5, 25, 3.5]))
    dbg = A.ev("([x,y])=>{const e=document.elementFromPoint(x,y);return [e.tagName+'#'+e.id+'.'+e.className, document.body.className, (e.closest('[id]')||{}).id]}", s)
    A.tdrag(s, (s[0] + 10, s[1] - 60), steps=20)
    p1 = S.comps()[1]["p"]
    chk("F3 parmakla pimi sürükle: eksen boyunca hareket eder, x,z sabit", abs(p1[1] - p0[1]) > 1 and abs(p1[0] - 30) < 0.05 and abs(p1[2] + 30) < 0.05, (p0, p1, dbg))
    # 4) geri al düğmesi
    A.undo()
    chk("F4 ↶ dokunma: sürükleme geri alınır", dist(S.comps()[1]["p"], p0) < 0.05, S.comps()[1]["p"])
    # 5) uzun basma bileşen menüsü → Gizle
    s = S.screen(S.world(PN["id"], [3.5, 25, 3.5]))
    A.longpress(s[0], s[1], 900)
    menu = A.ev("(()=>{const m=document.querySelector('.sw-ctx');return m?m.innerText:''})()")
    chk("F5 uzun basma: bileşen menüsü", "Gizle" in menu, menu.replace("\n", " | ")[:200])
    if "Gizle" in menu:
        A.pg.locator(".sw-ctx button:has-text('Gizle')").first.tap(); time.sleep(0.5)
        chk("F5 menüden Gizle", S.comps()[1]["hidden"])
        A.undo()
    # 6) Bileşeni Taşı paneli (Delta)
    S.select_comp("Pim<1>")
    A.cmd("Bileşeni Taşı")
    A.pmselect("Yöntem", "delta")
    A.pmfield("Y", 10)
    A.pmbtn("Uygula"); A.btn("#pm-ok"); A.wait(0.6)
    chk("F6 telefonda Taşı Delta Y=10 (eşleşme eksenine uygun)", abs(S.comps()[1]["p"][1] - (p0[1] + 10)) < 0.05, S.comps()[1]["p"])
    # ✕ dokunulabilir mi
    ok_x = A.ev("(()=>{const b=document.querySelector('#pm-cancel');if(!b||b.offsetParent===null)return 'gizli';const r=b.getBoundingClientRect();const e=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);return e===b||b.contains(e)})()")
    # 7) teknik resim telefonda: Montaj Resmi + parça resmi + kullanıcı ölçüsü dokunarak
    A.cmd("Parçaya Dön")
    setdoc(A, front_plate())
    T = TD(A)
    A.btn("#tabs button[data-tab='evaluate']"); A.cmd("Teknik Resim")
    for _ in range(120):
        time.sleep(0.25)
        if A.pg.locator("dialog.draw-dialog[open]").count() and T.svg():
            break
    time.sleep(0.6)
    vw = A.ev("(()=>{const d=document.querySelector('dialog.draw-dialog[open]');const r=d.getBoundingClientRect();return [r.width, innerWidth, d.scrollWidth]})()")
    chk("F7 teknik resim penceresi telefona sığar", vw[0] <= vw[1] + 1, vw)
    A.btn("dialog.draw-dialog[open] .td-tools button[data-tool='dim']")
    a = T.scroll_to("front", 0, 0); A.tap(a[0], a[1])
    b = T.scroll_to("front", 100, 0); A.tap(b[0], b[1])
    d = T.dr()
    chk("F7 telefonda dokunarak kullanıcı ölçüsü 100", len(d["user"]) == 1 and abs(abs(d["user"][0]["a"][0] - d["user"][0]["b"][0]) - 100) < 0.01, (d["user"], a, b))
    A.pg.screenshot(path=OUT + "/F_tel_resim.png")
    T.close()
    print("hatalar:", A.errs[:5])
    A.close()
    # 8) telefonda parça değişikliği → montaj (Eskizi düzenle: ölçüye çift dokunma)
    A = App(p, mobile=True); S = Asm(A)
    to_lib(A, pin_doc())
    setdoc(A, plate_doc())
    S.open(); P1 = S.add_current(); PN = S.add_lib("Pim")
    A.pg.locator(".vcube .iso").first.tap(); time.sleep(0.5)
    A.cmd("Eşleşme")
    S.click_local(PN["id"], [3.5, 20, 3.5]); S.click_local(P1["id"], [30 - 3.5, 8, -30 - 3.5])
    A.btn("#pm-ok"); A.wait(0.8)
    if S.pm_open():
        A.btn("#pm-cancel"); A.wait(0.4)
    chk("F8 pim delikte (x=30)", abs(S.comps()[1]["p"][0] - 30) < 0.05, S.comps()[1]["p"])
    A.btn("#tabs button[data-tab='features']"); A.wait(0.6)
    A.tact("Delik1", "Eskizi düzenle"); A.dim_dbl(0, 40); A.ok()
    A.btn("#tabs button[data-tab='asm']"); A.wait(2)
    chk("F8 telefonda delik 30→40 (Eskizi düzenle) → pim izler", abs(S.comps()[1]["p"][0] - 40) < 0.05, (S.comps()[1]["p"], A.toast()))
    A.reload(); S.open(); A.wait(1)
    chk("F8 yenile: montaj kalıcı (pim x=40)", abs(S.comps()[1]["p"][0] - 40) < 0.05, S.comps()[1]["p"])
    A.close()
finish()
