def near_face(pg, c):
    return pg.evaluate("""(c)=>{const m=window.__app.viewer.mesh; let b=-1,bd=1e9; m.faces.forEach((f,i)=>{const d=Math.hypot(f.c[0]-c[0],f.c[1]-c[1],f.c[2]-c[2]); if(d<bd){bd=d;b=i}}); return b}""", c)
def tap_face(pg, c):
    i = near_face(pg, c)
    sp = pg.evaluate(f"(()=>{{const v=window.__app.viewer; const sp=v.toScreen({c}); const rr=v.renderer.domElement.getBoundingClientRect(); return [rr.left+sp[0], rr.top+sp[1]]}})()")
    hit = pg.evaluate(f"JSON.stringify(window.__app.viewer.pick({sp[0]},{sp[1]},{{face:true}}))")
    pg.mouse.click(sp[0], sp[1]); time.sleep(0.5)
    return i, hit
